// The composite stress gauge is derived from the per-gate pressure readings so
// the header and the network-pulse dial can never drift from the node cards.
export const networkPressure = Number(
  (
    chokepoints.reduce((sum, entry) => sum + entry.summary.pressure, 0) / chokepoints.length
  ).toFixed(1),
)

export const networkTotals = chokepoints.reduce(
  (totals, entry) => ({
    active: totals.active + entry.summary.active,
    queue: totals.queue + entry.summary.queue,
    throughput: totals.throughput + entry.summary.throughput,
  }),
  { active: 0, queue: 0, throughput: 0 },
)

